"""Milestone 5: generate short commentary snippets with a sampling strategy.

The model outputs a probability for every possible next token. Picking the single most likely one every time
gets stuck in loops, so we sample from the distribution, shaped by three controls:
  temperature  divides the logits before the softmax (below 1 is safer and more repetitive, above 1 is wilder)
  top-k        keep only the k most likely tokens
  top-p        keep the smallest set of tokens whose probabilities add up to p (nucleus sampling)
"""
import re

import torch
import torch.nn.functional as F


def filter_logits(logits, top_k=None, top_p=None):
    "Set the logits of tokens outside the top-k / top-p set to -inf (logits is 1-D)."
    logits = logits.clone()
    if top_k is not None and 0 < top_k < logits.numel():
        kth = torch.topk(logits, top_k).values[-1]
        logits[logits < kth] = float("-inf")
    if top_p is not None and top_p < 1.0:
        sorted_logits, order = torch.sort(logits, descending=True)
        cum = F.softmax(sorted_logits, dim=-1).cumsum(-1)
        drop = cum > top_p
        drop[1:] = drop[:-1].clone()  # keep the token that crosses the threshold
        drop[0] = False               # always keep the most likely token
        logits[order[drop]] = float("-inf")
    return logits


@torch.no_grad()
def generate_ids(model, ids, max_new_tokens=60, temperature=0.8, top_k=40, top_p=0.9, eot_id=None, generator=None):
    "Extend a list of token ids. temperature 0 means always the most likely token."
    ids = list(ids)
    block = model.cfg.block_size
    for _ in range(max_new_tokens):
        logits = model(torch.tensor([ids[-block:]]))[0][0, -1]
        if temperature <= 0:
            nxt = int(logits.argmax())
        else:
            probs = F.softmax(filter_logits(logits / temperature, top_k, top_p), dim=-1)
            nxt = int(torch.multinomial(probs, 1, generator=generator))
        if nxt == eot_id:
            break  # the model decided the article is over
        ids.append(nxt)
    return ids


def finish_sentence(text):
    "Trim a snippet back to its last full sentence, if it has one, so it does not end mid-word."
    cut = max(text.rfind(". "), text.rfind('." '), text.rfind("! "), text.rfind("? "))
    if text.rstrip().endswith((".", "!", "?", '"')):
        return text.rstrip()
    return text[:cut + 1].rstrip() if cut > len(text) // 3 else text.rstrip()


def generate(model, tok, prompt, max_new_tokens=60, temperature=0.8, top_k=40, top_p=0.9, seed=None,
             trim=True):
    "Commentary for a prompt (a headline or the start of a sentence). Returns the prompt plus its continuation."
    generator = None
    if seed is not None:
        generator = torch.Generator().manual_seed(seed)
    ids = generate_ids(model, tok.encode(prompt), max_new_tokens, temperature, top_k, top_p,
                       eot_id=tok.eot_id, generator=generator)
    text = tok.decode(ids)
    return finish_sentence(text) if trim else text


def tidy(text):
    "Collapse stray spaces and blank lines for display."
    return re.sub(r"[ \t]+", " ", re.sub(r"\n{3,}", "\n\n", text)).strip()


def ngram_hashes(ids, n=8):
    "Hashes of every run of n consecutive token ids, to check generated text against the training corpus."
    return {hash(tuple(ids[i:i + n])) for i in range(len(ids) - n + 1)}


def copy_rate(ids, seen, n=8):
    "Share of the n-token runs in ids that appear verbatim in the training corpus (1.0 = pure copying)."
    runs = [hash(tuple(ids[i:i + n])) for i in range(len(ids) - n + 1)]
    return sum(r in seen for r in runs) / len(runs) if runs else 0.0


PROMPTS = [
    "Riverside FC and Harbor United: a late penalty decides the match\n",
    "Manchester United beat Real Madrid 2-1 in the Champions League final\n",
    "Local team wins the championship after dramatic overtime\n",
    "The home side scored in the 78th minute",
    "Star striker injured ahead of the season opener\n",
]
SETTINGS = [("greedy (temperature 0)", dict(temperature=0, top_k=None, top_p=None)),
            ("default (temperature 0.8, top-k 40, top-p 0.9)", dict(temperature=0.8, top_k=40, top_p=0.9)),
            ("wild (temperature 1.3)", dict(temperature=1.3, top_k=None, top_p=None))]


def main():
    "Write docs/samples.md: the same prompts under different sampling settings, plus a memorisation check."
    from pathlib import Path

    from app.bpe import BPETokenizer
    from app.corpus import load_corpus
    from app.model import load_model
    root = Path(__file__).resolve().parent.parent
    tok, model = BPETokenizer.load(root / "model" / "bpe.json"), load_model(root / "model" / "gpt.pt")
    corpus_ids = tok.encode(load_corpus())
    seen = ngram_hashes(corpus_ids)
    lines = ["# Sample commentary", "",
             "Generated by `python -m app.generate` with the trained model. Each prompt is a headline or the start "
             "of a sentence; the model continues it. Seeds are fixed, so these are repeatable.", ""]
    for prompt in PROMPTS:
        lines += [f"## {prompt.strip()}", ""]
        for name, opts in SETTINGS:
            text = tidy(generate(model, tok, prompt, max_new_tokens=70, seed=7, **opts))
            lines += [f"**{name}**", "", "> " + text.replace("\n", "\n> "), ""]
    rates = {}
    for name, opts in SETTINGS:
        scores = []
        for k, prompt in enumerate(PROMPTS * 4):
            ids = generate_ids(model, tok.encode(prompt), 100, eot_id=tok.eot_id,
                               generator=torch.Generator().manual_seed(k), **opts)
            scores.append(copy_rate(ids[len(tok.encode(prompt)):], seen))
        rates[name] = sum(scores) / len(scores)
    lines += ["## Is it copying the training articles?", "",
              "Share of 8-token runs in 20 generations (100 tokens each) that appear word for word in the corpus:", "",
              "| setting | copied 8-token runs |", "|---|---|"]
    lines += [f"| {name} | {rate:.1%} |" for name, rate in rates.items()]
    (root / "docs").mkdir(exist_ok=True)
    (root / "docs" / "samples.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
